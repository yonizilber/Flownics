package com.yonizilber.flownics.data.local.media

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.ImageDecoder
import android.net.Uri
import android.os.Build
import androidx.core.content.FileProvider
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.IOException
import java.util.UUID
import javax.inject.Inject
import javax.inject.Singleton

class MediaTooLargeException(val limitBytes: Long) : IOException("Media file is larger than $limitBytes bytes")

/**
 * Exercise photos and videos live in the app's private storage (filesDir/media), never in shared
 * storage: picking goes through the system Photo Picker, so the app needs no storage permission,
 * and the copies stay valid even if the user deletes the originals from the gallery.
 */
@Singleton
class MediaStorage @Inject constructor(
    @ApplicationContext private val context: Context,
) {
    private val mediaDir: File get() = File(context.filesDir, MEDIA_DIR).apply { mkdirs() }

    fun file(name: String): File {
        // Names are generated by this class; reject anything that could point outside mediaDir.
        require(name.isNotBlank() && !name.contains('/') && !name.contains('\\') && name != "..") {
            "Invalid media file name: $name"
        }
        return File(mediaDir, name)
    }

    /** A content:// URI other apps (a video player) can open read-only. */
    fun shareableUri(name: String): Uri =
        FileProvider.getUriForFile(context, "${context.packageName}.media", file(name))

    /** Decodes, downscales to at most [MAX_IMAGE_EDGE_PX] and re-encodes as JPEG. Returns the file name. */
    suspend fun importImage(source: Uri): String = withContext(Dispatchers.IO) {
        val bitmap = decodeScaled(source)
        val name = "${UUID.randomUUID()}.jpg"
        file(name).outputStream().use { out ->
            if (!bitmap.compress(Bitmap.CompressFormat.JPEG, JPEG_QUALITY, out)) {
                throw IOException("Could not encode image")
            }
        }
        bitmap.recycle()
        name
    }

    /** Copies a video as-is, refusing files over [MAX_VIDEO_BYTES]. Returns the file name. */
    suspend fun importVideo(source: Uri): String = withContext(Dispatchers.IO) {
        val resolver = context.contentResolver
        val extension = when (resolver.getType(source)) {
            "video/webm" -> "webm"
            "video/3gpp" -> "3gp"
            else -> "mp4"
        }
        val name = "${UUID.randomUUID()}.$extension"
        val target = file(name)
        try {
            resolver.openInputStream(source).use { input ->
                input ?: throw IOException("Cannot open $source")
                target.outputStream().use { out ->
                    val buffer = ByteArray(64 * 1024)
                    var total = 0L
                    while (true) {
                        val read = input.read(buffer)
                        if (read < 0) break
                        total += read
                        if (total > MAX_VIDEO_BYTES) throw MediaTooLargeException(MAX_VIDEO_BYTES)
                        out.write(buffer, 0, read)
                    }
                }
            }
        } catch (e: IOException) {
            target.delete()
            throw e
        }
        name
    }

    suspend fun copy(name: String): String = withContext(Dispatchers.IO) {
        val copyName = "${UUID.randomUUID()}.${name.substringAfterLast('.', "bin")}"
        file(name).copyTo(file(copyName))
        copyName
    }

    /** Copies a checked file from an import into the media folder under a new name. Returns the name. */
    suspend fun adopt(source: File, extension: String): String = withContext(Dispatchers.IO) {
        val name = "${UUID.randomUUID()}.$extension"
        source.copyTo(file(name))
        name
    }

    /** After a restore: every media file not in [keep] belonged to the replaced data. */
    suspend fun deleteAllExcept(keep: Set<String>) = withContext(Dispatchers.IO) {
        mediaDir.listFiles().orEmpty().filter { it.isFile && it.name !in keep }.forEach { it.delete() }
    }

    suspend fun delete(names: Collection<String>) = withContext(Dispatchers.IO) {
        names.forEach { file(it).delete() }
    }

    /** For ViewModel.onCleared, where there is no coroutine scope left to suspend in. */
    fun deleteNow(names: Collection<String>) {
        names.forEach { file(it).delete() }
    }

    private fun decodeScaled(source: Uri): Bitmap {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
            val decoderSource = ImageDecoder.createSource(context.contentResolver, source)
            return ImageDecoder.decodeBitmap(decoderSource) { decoder, info, _ ->
                val longest = maxOf(info.size.width, info.size.height)
                if (longest > MAX_IMAGE_EDGE_PX) {
                    val scale = MAX_IMAGE_EDGE_PX.toFloat() / longest
                    decoder.setTargetSize((info.size.width * scale).toInt(), (info.size.height * scale).toInt())
                }
                decoder.allocator = ImageDecoder.ALLOCATOR_SOFTWARE
            }
        }
        val resolver = context.contentResolver
        val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        resolver.openInputStream(source).use { BitmapFactory.decodeStream(it, null, bounds) }
        var sample = 1
        while (maxOf(bounds.outWidth, bounds.outHeight) / (sample * 2) >= MAX_IMAGE_EDGE_PX) sample *= 2
        val options = BitmapFactory.Options().apply { inSampleSize = sample }
        return resolver.openInputStream(source).use { BitmapFactory.decodeStream(it, null, options) }
            ?: throw IOException("Could not decode image $source")
    }

    companion object {
        private const val MEDIA_DIR = "media"
        private const val MAX_IMAGE_EDGE_PX = 1600
        private const val JPEG_QUALITY = 85

        // Keeps a shared export file reasonable; longer clips belong on YouTube as a link.
        const val MAX_VIDEO_BYTES = 100L * 1024 * 1024
    }
}
